#!/usr/bin/env python3
"""Recover the MSHookMessageEx table from the original xxhook dylib.

Usage:
  hookmap.py <dylib> [--json out.json] [--header out.h]

The dylib is a classic Logos/CydiaSubstrate build: a single constructor walks
objc_getClass() + @selector() and calls MSHookMessageEx(). We decode the
constructor, resolve selectors through __objc_selrefs (arm64e chained
fixups), and classify every replacement IMP by what it actually does.
"""
import argparse
import json
import struct

import lief
from capstone import CS_ARCH_ARM64, CS_MODE_ARM, Cs

STUB_GETCLASS = 0x798C
STUB_HOOK = 0x796C
STUB_OBJECT_GETCLASS = 0x79BC


class Dylib:
    def __init__(self, path):
        self.path = path
        self.raw = open(path, "rb").read()
        self.bin = lief.parse(path)
        self.text = next(s for s in self.bin.sections if s.name == "__text")
        self._insns = None

    def off(self, va):
        for seg in self.bin.segments:
            if seg.virtual_address <= va < seg.virtual_address + seg.virtual_size:
                o = seg.file_offset + (va - seg.virtual_address)
                if 0 <= o < len(self.raw):
                    return o
        return None

    def cstr(self, va):
        o = self.off(va)
        if o is None:
            return None
        e = self.raw.find(b"\0", o)
        try:
            return self.raw[o:e].decode("utf-8")
        except UnicodeDecodeError:
            return None

    def ptr(self, slot):
        o = self.off(slot)
        if o is None:
            return 0
        v = struct.unpack("<Q", self.raw[o:o + 8])[0]
        return v & 0x7FFFFFFFFFF  # arm64e chained rebase, low 43 bits

    @property
    def insns(self):
        if self._insns is None:
            md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
            code = self.raw[self.text.offset:self.text.offset + self.text.size]
            self._insns = list(md.disasm(code, self.text.virtual_address))
        return self._insns

    def classify(self, addr):
        seq = []
        for ins in self.insns:
            if ins.address < addr:
                continue
            if seq and ins.address >= addr + 0x40:
                break
            seq.append(ins)
            if ins.mnemonic in ("ret", "retab") and len(seq) > 1:
                break
        txt = "; ".join(f"{i.mnemonic} {i.op_str}".strip() for i in seq)
        if seq and seq[0].mnemonic in ("ret", "retab"):
            return "void"
        if "mov x0, #0" in txt and "ret" in txt:
            return "nil"
        if "mov w0, #0" in txt and "ret" in txt:
            return "NO"
        if "adr x0, #0x8030" in txt:
            return "return-2-string"
        if "braaz" in txt:
            return "pass-through"
        if "blraaz" in txt:
            return "call-orig"
        return "other:" + txt

    def hooks(self):
        regs = {}
        out = []
        for ins in self.insns:
            m, ops = ins.mnemonic, [o.strip() for o in ins.op_str.split(",")]
            if m in ("adrp", "adr"):
                try:
                    regs[ops[0]] = int(ops[1].lstrip("#"), 0)
                except (IndexError, ValueError):
                    pass
            elif m == "ldr" and len(ops) == 2:
                try:
                    regs[ops[0]] = int(ops[1].lstrip("#"), 0)
                except ValueError:
                    pass
            elif m == "mov" and len(ops) == 2:
                regs[ops[0]] = regs.get(ops[1])
            elif m == "bl":
                tgt = int(ops[0].lstrip("#"), 0)
                if tgt == STUB_GETCLASS:
                    regs["x0"] = "@" + str(self.cstr(regs.get("x0")))
                elif tgt == STUB_HOOK:
                    cls = regs.get("x0")
                    sel = self.cstr(self.ptr(regs.get("x1"))) if isinstance(regs.get("x1"), int) else None
                    impl = regs.get("x2")
                    slot = regs.get("x3")
                    out.append({
                        "class": str(cls).lstrip("@"),
                        "selector": sel,
                        "impl": hex(impl) if isinstance(impl, int) else str(impl),
                        "slot": hex(slot) if isinstance(slot, int) else str(slot),
                        "behavior": self.classify(impl) if isinstance(impl, int) else "?",
                    })
                    regs["x0"] = None
        return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dylib")
    ap.add_argument("--json")
    ap.add_argument("--header")
    args = ap.parse_args()

    d = Dylib(args.dylib)
    hooks = d.hooks()
    if args.json:
        with open(args.json, "w") as f:
            json.dump(hooks, f, indent=2, ensure_ascii=False)
    if args.header:
        with open(args.header, "w") as f:
            f.write("/* generated by tools/hookmap.py - do not edit */\n")
            f.write("typedef struct { const char *cls; const char *sel; const char *behavior; } amap_hook_t;\n")
            f.write("static const amap_hook_t kOrigHooks[] = {\n")
            for h in hooks:
                f.write('    {"%s", "%s", "%s"},\n' % (h["class"], h["selector"], h["behavior"]))
            f.write("};\n")
    for h in hooks:
        print(f"{h['class']:<28} {h['selector']:<56} {h['impl']:<8} {h['behavior']}")
    print(f"\n{len(hooks)} hooks")


if __name__ == "__main__":
    main()
